#!/usr/bin/env python3
"""Regenerate the dsh ported layer from the upstream Claude Code layer.

Deterministic and idempotent: same upstream input, same output. It exists so the
divergence stays mechanical instead of hand-maintained — when upstream moves, merge
`upstream/master`, re-run this, and review the diff of `.dsh/skills/`.

    python3 tools/port_skills_to_dsh.py

Reads  `.claude/skills/**`  ->  writes `.dsh/skills/**`

What it rewrites, and why each mapping is what it is:

- Tool vocabulary. dsh's tool names were read off a live session request
  (`request/header` + `tool/call` events), not the documentation: `web_search`,
  `web_fetch`, `ask_user_question`, `subagent`, `subagent_fork`, plus `read`, `write`,
  `edit`, `bash`, `glob`, `grep`, `todo_write`, `skill`, `workflow`. The last seven are
  identical to Claude Code's, so only four identifiers actually change.
- Paths. The ported layer is self-referential: `.claude/skills/` becomes `.dsh/skills/`,
  and a `.claude/commands/<name>.md` reference becomes `.dsh/skills/<name>/SKILL.md`.
- Frontmatter. `allowed-tools`, `context`, `sources` and `model` are Claude Code keys
  with no dsh equivalent — dsh governs tool access through sandbox/permission presets
  instead. They are dropped, and a `ported_from` line is added for provenance.
  `framework_version` is deliberately preserved: `tools/check_upstream_updates.py` reads
  it, and it is what keeps upstream tracking working on the ported copies.

Not handled here, on purpose — these need judgement, not substitution:

- `09-web-research.md`'s escalation rule is built on `WebFetch`'s `Claude-User` user agent
  and its robots.txt behaviour, which `tools/robots_check.py` gates the curl retry on.
  Renaming the tool does not rename the behaviour.
- `commands/apply.md`'s rule that any mention of AI tooling must name "Claude Code", and
  the "Generated by Claude Code" footer in `commands/html-report.md`.
"""
from __future__ import annotations

import pathlib
import re
import sys

REPO = (
    pathlib.Path(sys.argv[1]).resolve()
    if len(sys.argv) > 1
    else pathlib.Path(__file__).resolve().parents[1]
)
SRC = REPO / ".claude" / "skills"
DST = REPO / ".dsh" / "skills"

# Order matters: the prose form has to go before the bare identifier.
RENAMES = [
    (r"\bthe \*\*Agent tool\*\*", "the **subagent** tool"),
    (r"\bAgent tool\b", "subagent tool"),
    (r"\bAskUserQuestion\b", "ask_user_question"),
    (r"\bWebSearch\b", "web_search"),
    (r"\bWebFetch\b", "web_fetch"),
]

PATH_MAPS = [
    (r"\.claude/skills/", ".dsh/skills/"),
    (r"\.claude/commands/([a-z-]+)\.md", r".dsh/skills/\1/SKILL.md"),
]

FM_DROP = re.compile(r"^(allowed-tools|context|sources|model):.*\n", re.M)
FM_NOTE = "ported_from: .claude/skills/{rel}\n"


def convert(text: str, rel: str) -> tuple[str, dict[str, int]]:
    counts: dict[str, int] = {}
    for pat, rep in RENAMES + PATH_MAPS:
        text, n = re.subn(pat, rep, text)
        if n:
            counts[pat] = counts.get(pat, 0) + n

    if text.startswith("---\n"):
        end = text.find("\n---", 4)
        if end != -1:
            # head ends right before the closing "\n---" and so has no trailing
            # newline; a line-anchored regex would miss the last key, which is how
            # allowed-tools survives in files where it is the final frontmatter line.
            head, body = text[:end] + "\n", text[end:]
            dropped = len(FM_DROP.findall(head))
            head = FM_DROP.sub("", head)
            if dropped:
                counts["frontmatter keys dropped"] = dropped
            head = head.rstrip("\n") + "\n" + FM_NOTE.format(rel=rel)
            text = head + body
    return text, counts


def main() -> int:
    if not SRC.is_dir():
        print(f"missing source: {SRC}", file=sys.stderr)
        return 1
    written = 0
    totals: dict[str, int] = {}
    for src in sorted(SRC.rglob("*.md")):
        rel = src.relative_to(SRC).as_posix()
        out = DST / src.relative_to(SRC)
        out.parent.mkdir(parents=True, exist_ok=True)
        text, counts = convert(src.read_text(encoding="utf-8"), rel)
        out.write_text(text, encoding="utf-8")
        written += 1
        for k, v in counts.items():
            totals[k] = totals.get(k, 0) + v
        if counts:
            print(f"  {rel:<52} " + ", ".join(f"{k}×{v}" for k, v in counts.items()))
    print(f"\nfiles written: {written}")
    if not totals:
        print("no substitutions — the upstream layer may have changed shape")
    else:
        print("totals:", totals)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
